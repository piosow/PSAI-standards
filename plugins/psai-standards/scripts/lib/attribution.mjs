// Wzorce atrybucji AI w wiadomościach commitów.
// UWAGA: ta sama lista jest w templates/githooks/commit-msg (POSIX sh) — zmieniaj obie naraz.
// Wzorce celowo NIE łapią samego słowa "claude"/"gemini" w treści, bo projekt może o nich mówić
// (np. "feat(router): add Claude Haiku fallback") — blokujemy tylko atrybucję.

export const ATTRIBUTION_PATTERNS = [
  // Trailery współautorstwa wskazujące na narzędzie AI
  /^\s*co-authored-by:.*(claude|anthropic|openai|chatgpt|gpt-\d|copilot|gemini|bard|codex|cursor|devin|aider|windsurf|codeium|tabnine|noreply@anthropic\.com)/im,
  // Stopki typu "Generated with Claude Code" / "Generated by ChatGPT"
  /generated\s+(with|by|using)\s+.*(claude|chatgpt|openai|copilot|gemini|codex|cursor|\bai\b|\bllm\b)/im,
  // Dedykowane trailery sesji / asysty
  /^\s*(claude-session|ai-assisted|assisted-by|generated-by|ai-generated)\s*:/im,
  // Linki do sesji narzędzi AI
  /claude\.ai\/code/i,
  /chatgpt\.com\/(c|share)\//i,
  // Emoji robota używane w stopkach narzędzi
  /\u{1F916}/u,
];

/** Zwraca pierwszy dopasowany fragment albo null. */
export function findAttribution(text) {
  if (!text) return null;
  for (const re of ATTRIBUTION_PATTERNS) {
    const m = text.match(re);
    if (m) return m[0].trim();
  }
  return null;
}
